"""Regenerate docs/TOOLS.md from the live tool definitions.

    uv run python scripts/gen_tool_docs.py

The reference is built from exactly what an AI client receives from ``tools/list`` (name,
description, JSON schema), so it can never drift from the code. Run it after adding or
changing a tool, and commit the result.
"""

from __future__ import annotations

import asyncio
from pathlib import Path
from typing import Any

from libreoffice_mcp import formats
from libreoffice_mcp.app import build_server
from libreoffice_mcp.config import Settings
from libreoffice_mcp.tools import registry

OUT = Path(__file__).resolve().parent.parent / "docs" / "TOOLS.md"
PIPE = " \\| "  # a bare pipe would end the Markdown table cell
SECTIONS = [
    ("core", "Core tools (any document type)"),
    ("writer", "Writer tools (text documents: .odt .docx .doc .rtf .txt)"),
    ("calc", "Calc tools (spreadsheets: .ods .xlsx .xls .csv)"),
    ("impress", "Impress tools (presentations: .odp .pptx .ppt)"),
]
MODE_LABEL = {
    "read": "read-only",
    "create": "creates a file",
    "edit": "edits the document",
    "destructive": "edits the document (destructive)",
}


def type_of(schema: dict[str, Any]) -> str:
    """A short human-readable type for a JSON-schema fragment."""
    if "enum" in schema:
        return PIPE.join(f"`{v}`" for v in schema["enum"])
    options = schema.get("anyOf") or schema.get("oneOf")
    if options:
        parts = [type_of(o) for o in options if o.get("type") != "null"]
        return PIPE.join(dict.fromkeys(parts)) or "any"
    kind = schema.get("type", "object" if "$ref" in schema else "any")
    if kind == "array":
        return f"list of {type_of(schema.get('items', {}))}"
    return str(kind)


def first_sentence(text: str) -> str:
    paragraph = " ".join((text or "").strip().split("\n\n")[0].split())
    return paragraph.split(". ")[0].rstrip(".") + "."


def render_tool(tool: Any, mode: str) -> str:
    schema = tool.input_schema
    required = set(schema.get("required", []))
    lines = [
        f"### `{tool.name}`",
        "",
        f"*{MODE_LABEL[mode]}*",
        "",
        (tool.description or "").strip(),
        "",
    ]
    props = schema.get("properties", {})
    if props:
        lines += ["| Parameter | Type | Required | Notes |", "|---|---|---|---|"]
        for name, prop in props.items():
            note = (prop.get("description") or "").replace("\n", " ").replace("|", "\\|")
            default = prop.get("default")
            extra = f" Default: `{default}`." if default is not None else ""
            req = "yes" if name in required else ""
            lines.append(f"| `{name}` | {type_of(prop)} | {req} | {note}{extra} |")
        lines.append("")
    return "\n".join(lines)


async def main() -> None:
    server = build_server(Settings())
    listed = {t.name: t for t in await server.list_tools()}
    modes = {t.name: (t.app, t.mode) for t in registry.TOOLS}
    out = [
        "# Tool reference",
        "",
        "_Generated by `scripts/gen_tool_docs.py` - do not edit by hand._",
        "",
        f"{len(listed)} tools. Paths may be absolute or relative to the default documents folder. "
        "Editing tools save the file immediately and atomically. "
        "See the [README](../README.md) for how to expose only some of them.",
        "",
        f"Editable formats: {', '.join('`.' + e + '`' for e in formats.editable_extensions())}.",
        "",
    ]
    for app, title in SECTIONS:
        names = sorted(n for n, (a, _) in modes.items() if a == app and n in listed)
        if not names:
            if app in ("calc", "impress"):
                out += [f"## {title}", "", "_Planned - not implemented yet._", ""]
            continue
        out += [f"## {title}", ""]
        out += [f"- [`{n}`](#{n}) - {first_sentence(listed[n].description)}" for n in names]
        out.append("")
        out += [render_tool(listed[n], modes[n][1]) for n in names]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT} ({len(listed)} tools)")


if __name__ == "__main__":
    asyncio.run(main())
